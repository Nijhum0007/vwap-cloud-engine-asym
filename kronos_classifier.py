import os
import sys
import numpy as np
import torch
import warnings

warnings.filterwarnings('ignore')

# Add Kronos to path
sys.path.append(os.path.join(os.path.dirname(__file__), 'Kronos'))
from model.kronos import Kronos

class KronosSoftmaxEngine:
    def __init__(self, target_move=0.0015):
        """
        Initializes the REAL Kronos PyTorch Classification Engine.
        Loads the neural network weights generated by the training script.
        """
        print("[*] Initializing REAL Kronos PyTorch Classification Engine...")
        self.target_move = target_move
        self.device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
        
        # 1. Initialize the Base PyTorch Architecture
        self.model = Kronos(
            s1_bits=8, s2_bits=8, n_layers=4, d_model=128, n_heads=4, 
            ff_dim=512, ffn_dropout_p=0.1, attn_dropout_p=0.1, 
            resid_dropout_p=0.1, token_dropout_p=0.1, learn_te=False,
            in_features=4
        ).to(self.device)
        
        # 2. Load the trained weights!
        weights_path = os.path.join(os.path.dirname(__file__), 'kronos_trained_weights.pth')
        if os.path.exists(weights_path):
            print(f"[*] Loading trained AI weights from {weights_path}...")
            self.model.load_state_dict(torch.load(weights_path, map_location=self.device))
        else:
            print("[!] WARNING: Trained weights not found. You must run train_classifier.py first!")
            
        self.model.eval() # Set model to inference mode (disable dropout)
        print(f"[*] Real Engine Ready. Target Buckets set to +/- {self.target_move * 100:.3f}%")

    def _softmax(self, logits):
        """Standard Softmax function to convert raw AI output (logits) into percentages totaling 100%."""
        exp_logits = np.exp(logits - np.max(logits)) # Subtract max for numerical stability
        return exp_logits / exp_logits.sum()

    def predict(self, df):
        """
        Takes the live 1-minute historical dataframe, extracts the sequence, 
        and passes it into the PyTorch Neural Network.
        
        :param df: pandas DataFrame of live candle data
        :return: dict with 'Long', 'Short', 'Flat' percentages.
        """
        if len(df) < 60:
            # Not enough historical data yet to form a 60-minute sequence
            return {'Long': 0.0, 'Short': 0.0, 'Flat': 1.0}
            
        # 1. Extract the features
        prices = df['close'].tail(60).values
        dist_vwap = df['Dist_to_VWAP'].tail(60).values if 'Dist_to_VWAP' in df.columns else np.zeros_like(prices)
        vol_surge = df['Volume_Surge'].tail(60).values if 'Volume_Surge' in df.columns else np.zeros_like(prices)
        momentum = df['Momentum_5'].tail(60).values if 'Momentum_5' in df.columns else np.zeros_like(prices)
        
        # 2. LOCAL Z-SCORE NORMALIZATION on ALL features (must match training exactly)
        # This ensures all features have comparable scale (~std=1) so the neural network
        # can see dist_vwap and momentum, which are 3 orders of magnitude smaller than price.
        prices = (prices - np.mean(prices)) / (np.std(prices) + 1e-5)
        dist_vwap = (dist_vwap - np.mean(dist_vwap)) / (np.std(dist_vwap) + 1e-5)
        vol_surge = (vol_surge - np.mean(vol_surge)) / (np.std(vol_surge) + 1e-5)
        momentum = (momentum - np.mean(momentum)) / (np.std(momentum) + 1e-5)
        
        # 3. Stack into [60, 4] Matrix
        matrix = np.column_stack((prices, dist_vwap, vol_surge, momentum))
        
        # 4. Convert to Tensor. Shape: [1, 60, 4]
        seq_tensor = torch.tensor(matrix, dtype=torch.float32).unsqueeze(0).to(self.device)
        
        # 4. Neural Network Inference!
        with torch.no_grad(): # Don't calculate gradients during live trading (saves massive RAM and speeds up execution)
            logits_tensor = self.model.classify_continuous(seq_tensor)
            
        logits = logits_tensor.cpu().numpy()[0]
        
        # 5. Process through Softmax to get exactly 100% distribution
        probabilities = self._softmax(logits)
        
        return {
            'Long': float(probabilities[0]),
            'Short': float(probabilities[1]),
            'Flat': float(probabilities[2])
        }

